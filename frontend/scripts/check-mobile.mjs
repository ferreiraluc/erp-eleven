import assert from 'node:assert/strict'
import { readFileSync, existsSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')
const result = spawnSync(process.execPath, ['scripts/check-build.mjs', 'dist-mobile'], { cwd: root, stdio: 'inherit' })
assert.equal(result.status, 0, 'Mobile bundle is incomplete')
const build = JSON.parse(read('dist-mobile/mobile-build.json'))
assert.equal(new URL(build.apiOrigin).protocol, 'https:')
const html = read('dist-mobile/index.html')
assert(html.includes('viewport-fit=contain'), 'Native controls must stay inside the system safe area')
assert(!html.includes('viewport-fit=cover'), 'Edge-to-edge needs a separate CSS inset owner; do not enable it silently')
assert(html.includes('Content-Security-Policy'))
assert(html.includes(`connect-src 'self' ${build.apiOrigin}`))
assert(!html.includes("script-src 'self' 'unsafe-eval'"))
for (const path of ['android/app/src/main/assets/capacitor.config.json', 'ios/App/App/capacitor.config.json']) {
  assert(existsSync(new URL(`../${path}`, import.meta.url)), 'Run cap sync before mobile:check')
  const config = JSON.parse(read(path))
  assert.equal(config.appId, 'com.elevenparispy.erp')
  assert(!config.server.url, 'Production app must bundle its frontend, never load a remote server.url')
  assert.equal(config.server.cleartext, false)
  assert(!config.server.allowNavigation?.length, 'External pages must not get the native bridge')
  assert.equal(config.android.webContentsDebuggingEnabled, false)
  assert.equal(config.ios.webContentsDebuggingEnabled, false)
  assert.equal(config.plugins.SystemBars.insetsHandling, 'native')
  assert.equal(config.plugins.SystemBars.initialViewportFitValueHint, 'contain')
  assert.equal(config.plugins.SystemBars.style, 'LIGHT')
  assert.deepEqual(config.plugins.PushNotifications.presentationOptions, ['badge', 'sound', 'alert'])
  assert.equal(config.ios.contentInset, 'automatic')
}
const manifest = read('android/app/src/main/AndroidManifest.xml')
assert(manifest.includes('android:allowBackup="false"'))
assert(manifest.includes('android:usesCleartextTraffic="false"'))
assert(manifest.includes('android:name="com.google.firebase.messaging.default_notification_channel_id"'))
assert(manifest.includes('android:value="eleven-updates-v2"'))
const paths = read('android/app/src/main/res/xml/file_paths.xml')
assert(!paths.includes('external-path'))
assert(paths.includes('path="eleven-shared-pdf/"'))
assert(paths.includes('<external-files-path name="eleven_camera" path="Pictures/"'))
assert(!paths.includes('path="."') && !paths.includes('path="/"'))
const cameraPaths = read('android/app/src/main/res/xml/ioncamera_paths.xml')
assert(cameraPaths.includes('<cache-path name="eleven_camera_cache" path="."'))
assert(!/<(?:files|external(?:-files|-cache|-media)?|root)-path\b/.test(cameraPaths), 'Camera provider may expose only its private cache, not persistent or external files')
assert(manifest.includes('android:requestLegacyExternalStorage="false"'))
assert(read('android/variables.gradle').includes("kotlin_version = '2.4.20'"))
assert(read('android/gradle/wrapper/gradle-wrapper.properties').includes('gradle-8.14.7-all.zip'))
assert(read('android/gradle/wrapper/gradle-wrapper.properties').includes('distributionSha256Sum=5def2b7c967555e01ea4bbafdc829b6519edc81a4ab4ff4cccc08c1e42c4f6c0'))
assert(read('android/build.gradle').includes("tasks.register('verifyNativeSecurityVersions')"))
assert(read('ios/App/App/Info.plist').includes('NSCameraUsageDescription'))
assert(read('ios/App/App/Info.plist').includes('NSPhotoLibraryUsageDescription'))
assert(read('ios/App/App/Info.plist').includes('NSPhotoLibraryAddUsageDescription'))
assert(read('ios/App/App/PrivacyInfo.xcprivacy').includes('C617.1'))
console.log('Mobile: bundled assets, HTTPS, restricted bridge/files, camera and privacy manifest verified')
